export type MessageKey = keyof typeof catalog;
export type Locale = 'zh-CN' | 'en';
export type Language = 'auto' | Locale;
export type Params = Record<string,string|number>;
export function resolveLocale(language:Language='auto',nativeLanguage?:string|null,webLanguages:readonly string[]=[]):Locale {
 if(language==='zh-CN'||language==='en')return language;
 const system=nativeLanguage?.trim()||webLanguages.find(value=>value.trim())||'en';
 return /^zh(?:-|$)/i.test(system)?'zh-CN':'en';
}
export function translate(key:MessageKey,resolved:Locale,params:Params={}):string {
 const text=resolved==='zh-CN'?catalog[key]:key;
 return text.replace(/\{(\w+)\}/g,(placeholder,name)=>Object.hasOwn(params,name)?String(params[name]):placeholder);
}
export function localizeValue(value:string,resolved:Locale):string { return Object.hasOwn(catalog,value)?translate(value as MessageKey,resolved):value; }
export function formatNumber(value:unknown,resolved:Locale,digits=0):string {return typeof value==='number'&&Number.isFinite(value)?new Intl.NumberFormat(resolved,{maximumFractionDigits:digits}).format(value):translate('Unavailable',resolved);}
export function formatDate(value:number|string|Date|null|undefined,resolved:Locale,options?:Intl.DateTimeFormatOptions):string {if(value==null)return translate('Unavailable',resolved);const date=new Date(value);return Number.isFinite(date.getTime())?new Intl.DateTimeFormat(resolved,options??{year:'numeric',month:'numeric',day:'numeric',hour:'numeric',minute:'2-digit',second:'2-digit'}).format(date):translate('Unavailable',resolved);}

